    tts = gTTS(text=full_message, lang='en')
    tts.save("pro_alert.mp3")

    # 3. Convert to base64 for browser playback
    with open("pro_alert.mp3", "rb") as f:
        data = f.read()
        b64 = base64.b64encode(data).decode()

    # 4. Javascript to repeat exactly 5 times
    audio_html = f"""
    <audio id="farmAudio">
      <source src="data:audio/mp3;base64,{b64}" type="audio/mp3">
    </audio>
    <script>
      var audio = document.getElementById('farmAudio');
      var playCount = 0;
      var target = {repeat_count};

      audio.play();

      audio.onended = function() {{
        playCount++;
        if(playCount < target) {{
          setTimeout(function(){{ audio.play(); }}, 1000); // 1 second gap between repeats
        }}
      }};
    </script>
    """
    display(HTML(audio_html))
    print(f"🔊 System is speaking the alert {repeat_count} times...")

